const fs = require('fs');
const path = require('path');
const { REVIEWED_CHOICE_OVERRIDES } = require('./grammar-workshop-answer-overrides');

const root = path.resolve(__dirname, '..');
const output = path.join(
  root,
  'flutter_app/lib/features/workshop/grammar_workshop_answer_overrides.dart',
);

function dartString(value) {
  return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

const entries = [];
for (const [topicKey, questions] of Object.entries(REVIEWED_CHOICE_OVERRIDES)) {
  for (const [questionId, override] of Object.entries(questions)) {
    entries.push([
      `  ${dartString(`${topicKey}/${questionId}`)}: WorkshopChoiceAnswerOverride(`,
      `    acceptedAnswers: [${override.acceptedAnswers.map(dartString).join(', ')}],`,
      `    explanation: ${dartString(override.explanation)},`,
      ...(override.question ? [`    question: ${dartString(override.question)},`] : []),
      ...(override.chinese ? [`    chinese: ${dartString(override.chinese)},`] : []),
      ...(override.present ? [`    present: ${dartString(override.present)},`] : []),
      ...(override.past ? [`    past: ${dartString(override.past)},`] : []),
      ...(override.pp ? [`    pp: ${dartString(override.pp)},`] : []),
      ...(override.ing ? [`    ing: ${dartString(override.ing)},`] : []),
      ...(override.acceptedTokenSets ? [
        `    acceptedTokenSets: [${override.acceptedTokenSets.map((tokens) => `[${tokens.map(dartString).join(', ')}]`).join(', ')}],`,
      ] : []),
      '  ),',
    ].join('\n'));
  }
}

const source = `// Generated by scripts/generate-grammar-workshop-overrides-dart.js.\n` +
`// Edit scripts/grammar-workshop-answer-overrides.js, then regenerate.\n` +
`class WorkshopChoiceAnswerOverride {\n` +
`  const WorkshopChoiceAnswerOverride({\n` +
`    required this.acceptedAnswers,\n` +
`    required this.explanation,\n` +
`    this.question,\n` +
`    this.chinese,\n` +
`    this.present,\n` +
`    this.past,\n` +
`    this.pp,\n` +
`    this.ing,\n` +
`    this.acceptedTokenSets = const [],\n` +
`  });\n\n` +
`  final List<String> acceptedAnswers;\n` +
`  final String explanation;\n` +
`  final String? question;\n` +
`  final String? chinese;\n` +
`  final String? present;\n` +
`  final String? past;\n` +
`  final String? pp;\n` +
`  final String? ing;\n` +
`  final List<List<String>> acceptedTokenSets;\n` +
`}\n\n` +
`const grammarWorkshopChoiceAnswerOverrides =\n` +
`    <String, WorkshopChoiceAnswerOverride>{\n` +
`${entries.join('\n')}\n` +
`};\n`;

fs.writeFileSync(output, source);
console.log(`Generated ${entries.length} reviewed Workshop overrides -> ${output}`);
